// Keep the static HTML entry in source control. Dependency bundles are ignored
// and generated during development checks and release builds.
const root = fileURLToPath(new URL("../", import.meta.url));
const vendor = resolve(root, "web/vendor");
const library = dirname(fileURLToPath(import.meta.resolve("@zakisheriff/liquid-glass/styles.css")));
const assets = await build({
  absWorkingDir: root,
  entryPoints: [
    { in: "src/glass-controls.tsx", out: "liquid-glass" },
    { in: resolve(library, "index.css"), out: "liquid-glass" },
  ],
  outdir: vendor,
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2022",
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "inline",
  write: false,
});
const html = await format(
  "<!doctype html>\n<!-- Generated by desktop/renderer/src/render.tsx. -->\n" + renderToStaticMarkup(document),
  {
    parser: "html",
    printWidth: 240,
    htmlWhitespaceSensitivity: "ignore",
  },
);
const licenses = await Promise.all([
  ["Liquid Glass", resolve(library, "../LICENSE")],
  ["Liquid Glass third-party notices", resolve(library, "../THIRD_PARTY_NOTICES.md")],
  ...["react", "react-dom", "scheduler"].map(name => [name, resolve(root, "node_modules", name, "LICENSE")]),
].map(async ([name, file]) => name + "\n\n" + (await readFile(file, "utf8")).replaceAll("\r\n", "\n").trim()));
const outputs = [
  ...assets.outputFiles.map(file => ({ path: file.path, text: file.text })),
  { path: resolve(vendor, "liquid-glass-LICENSE.txt"), text: licenses.join("\n\n") + "\n" },
  { path: resolve(root, "web/index.html"), text: html },
];
await mkdir(vendor, { recursive: true });
for (const output of outputs) {
  if (process.argv.includes("--check") && output.path === resolve(root, "web/index.html")) {
    if (output.text !== (await readFile(output.path, "utf8")).replaceAll("\r\n", "\n")) {
      throw new Error(basename(output.path) + " is stale. Run npm --prefix desktop/renderer run build.");
    }
  } else {
    await writeFile(output.path, output.text);
  }
}
